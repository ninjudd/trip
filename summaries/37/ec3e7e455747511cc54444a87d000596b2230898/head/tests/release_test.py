#!/usr/bin/env python3
"""Checks of .github/scripts/release.py, the Release workflow's script.

Each case works in temporary directories: a copy of the version files, or a
clone of a temporary bare repository that stands in for GitHub, with a fake
`gh` on PATH that plays GitHub's releases. Nothing reaches the network.

Usage: python3 tests/release_test.py
"""

from __future__ import annotations

import importlib.util
import io
import os
import shutil
import subprocess
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("release", ROOT / ".github" / "scripts" / "release.py")
assert spec and spec.loader
release = importlib.util.module_from_spec(spec)
spec.loader.exec_module(release)

FAKE_GH = r"""#!/usr/bin/env bash
# Plays GitHub's releases: $FAKE_GH_DIR/releases lists the tags that have one.
# Logs one line per call to $FAKE_GH_DIR/calls.log. With FAKE_GH_FAIL set to a
# command such as "release create", that command fails as GitHub refusing it.
set -u
printf '%s\n' "$*" >> "$FAKE_GH_DIR/calls.log"
if [ "$1 $2" = "${FAKE_GH_FAIL:-}" ]; then
  echo "HTTP 403: Resource not accessible by integration" >&2
  exit 1
fi
case "$1 $2" in
  "release view")
    if grep -qxF "$3" "$FAKE_GH_DIR/releases" 2>/dev/null; then
      printf '{"tagName":"%s"}\n' "$3"
    else
      echo "release not found" >&2
      exit 1
    fi ;;
  "release create") printf '%s\n' "$3" >> "$FAKE_GH_DIR/releases" ;;
  *) echo "fake gh: unexpected $*" >&2; exit 2 ;;
esac
"""

# A Cargo.lock whose first package also names 0.5.0, so a bump that rewrites
# the first version line it finds rewrites the wrong package.
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "anyhow"
version = "{version}"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "trip"
version = "{version}"
dependencies = [
 "anyhow",
]
"""

MANIFEST = """[package]
name = "trip"
version = "{version}"
edition = "2021"

[dependencies]
anyhow = "1"
"""


def run(cwd: Path, *args: str) -> str:
    return subprocess.run(list(args), cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def temporary_directory(case: unittest.TestCase) -> Path:
    path = Path(tempfile.mkdtemp(prefix="trip-release-"))
    case.addCleanup(shutil.rmtree, path, ignore_errors=True)
    return path


def write_version_files(root: Path, version: str) -> None:
    (root / "Cargo.toml").write_text(MANIFEST.format(version=version))
    (root / "Cargo.lock").write_text(LOCK.format(version=version))


class BumpTests(unittest.TestCase):
    def setUp(self) -> None:
        self.root = temporary_directory(self)

    def test_bumps_the_repository_version_files_and_nothing_else(self) -> None:
        for name in release.VERSION_FILES:
            shutil.copy(ROOT / name, self.root / name)
        before = {name: (self.root / name).read_text() for name in release.VERSION_FILES}
        start = release.current(release.reader(self.root))
        major, minor, _ = release.parse(start)
        new = f"{major}.{minor + 1}.0"

        self.assertEqual(new, release.bump(self.root, "minor"))

        self.assertEqual({"Cargo.toml": new, "Cargo.lock": new}, release.versions(release.reader(self.root)))
        self.assertEqual(before["Cargo.toml"].replace(f'\nversion = "{start}"\n', f'\nversion = "{new}"\n', 1),
                         (self.root / "Cargo.toml").read_text())
        entry = '[[package]]\nname = "trip"\nversion = "{}"\n'
        self.assertEqual(before["Cargo.lock"].replace(entry.format(start), entry.format(new)),
                         (self.root / "Cargo.lock").read_text())
        self.assertEqual(sorted(release.VERSION_FILES), sorted(path.name for path in self.root.iterdir()))

    def test_bumps_only_trips_entry_in_the_lock(self) -> None:
        write_version_files(self.root, "0.5.0")
        release.bump(self.root, "patch")
        lock = (self.root / "Cargo.lock").read_text()
        self.assertIn('name = "anyhow"\nversion = "0.5.0"\n', lock)
        self.assertIn('name = "trip"\nversion = "0.5.1"\n', lock)
        self.assertEqual(MANIFEST.format(version="0.5.1"), (self.root / "Cargo.toml").read_text())

    def test_bump_raises_one_part_and_resets_the_smaller_ones(self) -> None:
        for part, expected in (("patch", "1.2.4"), ("minor", "1.3.0"), ("major", "2.0.0")):
            with self.subTest(part=part):
                write_version_files(self.root, "1.2.3")
                self.assertEqual(expected, release.bump(self.root, part))
                self.assertEqual(expected, release.current(release.reader(self.root)))

    def test_bump_prints_only_the_new_version(self) -> None:
        write_version_files(self.root, "0.1.0")
        out = io.StringIO()
        with redirect_stdout(out):
            self.assertEqual(0, release.main(["bump", "minor"], root=self.root))
        self.assertEqual("0.2.0\n", out.getvalue())

    def test_fails_on_a_lock_with_no_trip_entry_and_writes_nothing(self) -> None:
        write_version_files(self.root, "0.1.0")
        lock = self.root / "Cargo.lock"
        lock.write_text(lock.read_text().replace('name = "trip"', 'name = "trap"'))
        before = {name: (self.root / name).read_text() for name in release.VERSION_FILES}
        err = io.StringIO()
        with redirect_stderr(err), redirect_stdout(io.StringIO()):
            self.assertEqual(1, release.main(["bump", "minor"], root=self.root))
        self.assertIn("Cargo.lock has no trip package entries", err.getvalue())
        self.assertEqual(before, {name: (self.root / name).read_text() for name in release.VERSION_FILES})

    def test_refuses_a_version_that_does_not_go_up(self) -> None:
        write_version_files(self.root, "0.5.0")
        with self.assertRaisesRegex(release.ReleaseError, "not above the current version"):
            release.set_version(self.root, "0.5.0")
        with self.assertRaisesRegex(release.ReleaseError, "not X.Y.Z"):
            release.set_version(self.root, "1.0")

    def test_refuses_files_that_disagree(self) -> None:
        write_version_files(self.root, "0.5.0")
        (self.root / "Cargo.lock").write_text(LOCK.format(version="0.4.0"))
        with self.assertRaisesRegex(release.ReleaseError, "the version files disagree"):
            release.bump(self.root, "patch")


def git_repo(path: Path) -> None:
    run(path.parent, "git", "init", "--quiet", str(path))
    for key, value in (("user.name", "Test"), ("user.email", "test@example.com"),
                       ("commit.gpgsign", "false"), ("tag.gpgsign", "false")):
        run(path, "git", "config", key, value)


class CheckCommitTests(unittest.TestCase):
    def setUp(self) -> None:
        self.repo = temporary_directory(self) / "repo"
        git_repo(self.repo)
        write_version_files(self.repo, "0.1.0")
        (self.repo / "src").mkdir()
        (self.repo / "src" / "main.rs").write_text("fn main() {}\n")
        run(self.repo, "git", "add", "-A")
        run(self.repo, "git", "commit", "--quiet", "-m", "start")

    def release_commit(self) -> None:
        run(self.repo, "git", "commit", "--quiet", "-am", "Release")

    def assert_refused(self, message: str) -> None:
        err = io.StringIO()
        with redirect_stderr(err), redirect_stdout(io.StringIO()):
            self.assertEqual(1, release.main(["check-commit"], root=self.repo))
        self.assertIn(message, err.getvalue())

    def test_accepts_a_commit_that_only_bumps_the_version(self) -> None:
        release.bump(self.repo, "minor")
        self.release_commit()
        out = io.StringIO()
        with redirect_stdout(out):
            self.assertEqual(0, release.main(["check-commit", "HEAD"], root=self.repo))
        self.assertEqual("the release commit changes only the version, to 0.2.0\n", out.getvalue())

    def test_refuses_a_commit_that_also_touches_src(self) -> None:
        release.bump(self.repo, "minor")
        (self.repo / "src" / "main.rs").write_text('fn main() { println!("unreviewed"); }\n')
        self.release_commit()
        self.assert_refused("the release commit changes Cargo.lock Cargo.toml src/main.rs, "
                            "not only Cargo.lock Cargo.toml")

    def test_refuses_a_commit_that_changes_more_than_the_version_in_a_version_file(self) -> None:
        release.bump(self.repo, "minor")
        manifest = self.repo / "Cargo.toml"
        manifest.write_text(manifest.read_text().replace('anyhow = "1"', 'anyhow = "1"\nlibc = "0.2"'))
        self.release_commit()
        self.assert_refused("the release commit changes Cargo.toml beyond its version")

    def test_refuses_a_commit_that_does_not_raise_the_version(self) -> None:
        for name in release.VERSION_FILES:
            path = self.repo / name
            path.write_text(path.read_text() + "\n")
        self.release_commit()
        self.assert_refused("moves the version from 0.1.0 to 0.1.0, not up")


def released_clone(tmp: Path) -> tuple[Path, Path]:
    """Build a bare remote and a clone of it whose `trunk` carries version 0.5.0."""
    remote = tmp / "remote.git"
    run(tmp, "git", "init", "--quiet", "--bare", str(remote))
    repo = tmp / "repo"
    git_repo(repo)
    run(repo, "git", "remote", "add", "origin", str(remote))
    commit_version(repo, "0.5.0")
    return remote, repo


def commit_version(repo: Path, version: str) -> str:
    """Commit `version` to the version files and push it to the remote's `trunk`."""
    write_version_files(repo, version)
    run(repo, "git", "add", "-A")
    run(repo, "git", "commit", "--quiet", "--allow-empty", "-m", version)
    # The branch is not main: a developer's pre-push hook may refuse pushes to main.
    run(repo, "git", "push", "--quiet", "origin", "HEAD:refs/heads/trunk")
    return run(repo, "git", "rev-parse", "HEAD")


class TagTests(unittest.TestCase):
    def setUp(self) -> None:
        tmp = temporary_directory(self)
        self.remote, self.repo = released_clone(tmp)
        self.github = tmp / "github"
        self.github.mkdir()
        bin_dir = tmp / "bin"
        bin_dir.mkdir()
        (bin_dir / "gh").write_text(FAKE_GH)
        (bin_dir / "gh").chmod(0o755)
        env = mock.patch.dict(os.environ, {"PATH": f"{bin_dir}{os.pathsep}{os.environ.get('PATH', '')}",
                                           "FAKE_GH_DIR": str(self.github)})
        env.start()
        self.addCleanup(env.stop)
        os.environ.pop("FAKE_GH_FAIL", None)
        # The test remote is a local path, which names no GitHub repository.
        slug = mock.patch.object(release, "repo_slug", return_value="test/trip")
        slug.start()
        self.addCleanup(slug.stop)

    def releases(self) -> list[str]:
        path = self.github / "releases"
        return path.read_text().split() if path.exists() else []

    def gh_calls(self) -> list[str]:
        path = self.github / "calls.log"
        return path.read_text().splitlines() if path.exists() else []

    def head(self) -> str:
        return run(self.repo, "git", "rev-parse", "HEAD")

    def commit_other_change(self) -> str:
        (self.repo / "notes.txt").write_text("not a release\n")
        run(self.repo, "git", "add", "-A")
        run(self.repo, "git", "commit", "--quiet", "-m", "notes")
        run(self.repo, "git", "push", "--quiet", "origin", "HEAD:refs/heads/trunk")
        return self.head()

    def remote_tags(self) -> list[str]:
        return run(self.remote, "git", "tag", "--list").split()

    def remote_tag(self, name: str) -> str:
        return run(self.remote, "git", "rev-parse", f"{name}^{{commit}}")

    def remote_tag_object(self, name: str) -> str:
        return run(self.remote, "git", "rev-parse", f"refs/tags/{name}")

    def tag(self, **kwargs: object) -> str:
        return release.tag(self.repo, branch="trunk", **kwargs)  # type: ignore[arg-type]

    def test_a_fresh_release_tags_publishes_and_moves_the_major_tag(self) -> None:
        first = self.head()
        self.assertEqual(f"v0.5.0 at {first[:9]}: tagged v0.5.0, published the GitHub release, moved v0",
                         self.tag())
        self.assertEqual(first, self.remote_tag("v0.5.0"))
        self.assertEqual(first, self.remote_tag("v0"))
        self.assertEqual("tag", run(self.remote, "git", "cat-file", "-t", "refs/tags/v0.5.0"), "an annotated tag")
        self.assertEqual(["v0.5.0"], self.releases())
        # --verify-tag keeps GitHub from making the tag itself when the push did not land.
        self.assertIn("release create v0.5.0 --verify-tag --generate-notes --repo test/trip", self.gh_calls())

        second = commit_version(self.repo, "0.5.1")
        self.tag()
        self.assertEqual(first, self.remote_tag("v0.5.0"), "a release tag never moves")
        self.assertEqual(second, self.remote_tag("v0.5.1"))
        self.assertEqual(second, self.remote_tag("v0"))
        self.assertEqual(["v0.5.0", "v0.5.1"], self.releases())

    def test_a_rerun_after_a_failure_between_the_tag_and_the_release_finishes_it(self) -> None:
        first = self.head()
        self.tag()
        second = commit_version(self.repo, "0.5.1")
        os.environ["FAKE_GH_FAIL"] = "release create"
        with self.assertRaisesRegex(release.ReleaseError,
                                    r"gh release create failed: HTTP 403.*Before that it tagged v0\.5\.1\. Run tag"):
            self.tag()
        tagged = self.remote_tag_object("v0.5.1")
        # trip upgrade installs the newest GitHub release while the installer
        # is served from v0, so v0 must not move before the release exists.
        self.assertEqual(first, self.remote_tag("v0"))

        del os.environ["FAKE_GH_FAIL"]
        self.assertEqual(f"v0.5.1 at {second[:9]}: published the GitHub release, moved v0 "
                         "(already done: the v0.5.1 tag)", self.tag())
        self.assertEqual(["v0", "v0.5.0", "v0.5.1"], self.remote_tags())
        self.assertEqual(tagged, self.remote_tag_object("v0.5.1"), "finishing a release never retags it")
        self.assertEqual(second, self.remote_tag("v0"))
        self.assertEqual(["v0.5.0", "v0.5.1"], self.releases())

    def test_tag_does_nothing_once_the_version_is_released(self) -> None:
        commit = self.head()
        self.tag()
        tagged, major = self.remote_tag_object("v0.5.0"), self.remote_tag_object("v0")
        self.assertEqual(f"v0.5.0 at {commit[:9]}: nothing to do "
                         "(already done: the v0.5.0 tag, the GitHub release, v0)", self.tag())
        self.assertEqual((tagged, major), (self.remote_tag_object("v0.5.0"), self.remote_tag_object("v0")))
        self.assertEqual(1, sum(call.startswith("release create") for call in self.gh_calls()))

    def test_a_push_that_leaves_the_version_alone_releases_nothing(self) -> None:
        # trip's 0.1.0 was never released, so a later Cargo.toml change that
        # keeps it must not publish 0.1.0.
        before = self.head()
        after = self.commit_other_change()
        self.assertEqual(f"{before[:9]}..{after[:9]} leaves the version at 0.5.0, so there is nothing to release",
                         self.tag(commit=after, since=before))
        self.assertEqual([], self.remote_tags())
        self.assertEqual([], self.gh_calls())

    def test_reverting_the_first_release_publishes_nothing(self) -> None:
        # 0.5.0 was never released, like trip's 0.1.0, so reverting the first
        # release pull request must not publish it or move v0 onto the revert.
        before = self.head()
        bump = commit_version(self.repo, "0.6.0")
        self.tag(commit=bump, since=before)
        calls = self.gh_calls()
        revert = commit_version(self.repo, "0.5.0")
        self.assertEqual(f"{bump[:9]}..{revert[:9]} lowers the version from 0.6.0 to 0.5.0, "
                         "so there is nothing to release", self.tag(commit=revert, since=bump))
        self.assertEqual(["v0", "v0.6.0"], self.remote_tags())
        self.assertEqual(bump, self.remote_tag("v0"))
        self.assertEqual(calls, self.gh_calls())

    def test_reverting_a_later_release_publishes_nothing_and_leaves_v0(self) -> None:
        self.tag()
        bump = commit_version(self.repo, "0.6.0")
        self.tag()
        tags = {name: self.remote_tag_object(name) for name in self.remote_tags()}
        revert = commit_version(self.repo, "0.5.0")
        self.assertIn("lowers the version from 0.6.0 to 0.5.0", self.tag(commit=revert, since=bump))
        self.assertEqual(tags, {name: self.remote_tag_object(name) for name in self.remote_tags()})
        self.assertEqual(bump, self.remote_tag("v0"))

    def test_refuses_a_new_version_below_the_newest_release(self) -> None:
        # After a revert to 0.5.0, the next release pull request bumps to
        # 0.5.1, which is older than the released 0.6.0.
        self.tag()
        bump = commit_version(self.repo, "0.6.0")
        self.tag()
        revert = commit_version(self.repo, "0.5.0")
        self.tag(commit=revert, since=bump)
        calls = self.gh_calls()
        lower = commit_version(self.repo, "0.5.1")
        with self.assertRaisesRegex(release.ReleaseError,
                                    r"v0\.6\.0 is already released, so 0\.5\.1 cannot be; set a version above 0\.6\.0"):
            self.tag(commit=lower, since=revert)
        self.assertEqual(["v0", "v0.5.0", "v0.6.0"], self.remote_tags())
        self.assertEqual(bump, self.remote_tag("v0"))
        self.assertEqual(calls, self.gh_calls())

    def test_finishing_an_older_release_leaves_v0_on_a_newer_one(self) -> None:
        self.tag()
        first = self.head()
        older = commit_version(self.repo, "0.5.1")
        os.environ["FAKE_GH_FAIL"] = "release create"
        with self.assertRaises(release.ReleaseError):
            self.tag(commit=older, since=first)
        del os.environ["FAKE_GH_FAIL"]
        newer = commit_version(self.repo, "0.5.2")
        self.tag(commit=newer, since=older)
        self.assertEqual(f"v0.5.1 at {older[:9]}: published the GitHub release, left v0 on the newer 0.5.2 "
                         "(already done: the v0.5.1 tag)", self.tag(commit=older, since=first))
        self.assertEqual(newer, self.remote_tag("v0"))
        self.assertEqual(["v0.5.0", "v0.5.2", "v0.5.1"], self.releases())

    def test_tags_the_release_commit_even_after_the_branch_moves_past_it(self) -> None:
        before = self.head()
        bump = commit_version(self.repo, "0.5.1")
        self.commit_other_change()
        self.assertEqual(f"v0.5.1 at {bump[:9]}: tagged v0.5.1, published the GitHub release, moved v0",
                         self.tag(commit=bump, since=before))
        self.assertEqual(bump, self.remote_tag("v0.5.1"))
        self.assertEqual(bump, self.remote_tag("v0"))

    def test_refuses_a_release_commit_that_is_not_on_the_branch(self) -> None:
        side = run(self.repo, "git", "commit-tree", "HEAD^{tree}", "-p", "HEAD", "-m", "side")
        with self.assertRaisesRegex(release.ReleaseError, f"{side} is not on origin/trunk"):
            self.tag(commit=side)
        self.assertEqual([], self.remote_tags())

    def test_refuses_a_version_tag_that_is_not_on_the_branch(self) -> None:
        side = run(self.repo, "git", "commit-tree", "HEAD^{tree}", "-p", "HEAD", "-m", "side")
        run(self.repo, "git", "tag", "-a", "v0.5.0", side, "-m", "v0.5.0")
        run(self.repo, "git", "push", "--quiet", "origin", "refs/tags/v0.5.0")
        with self.assertRaisesRegex(release.ReleaseError, f"v0.5.0 already names {side[:9]}, which is not in"):
            self.tag()
        self.assertEqual(["v0.5.0"], self.remote_tags(), "a refusal moves no tag")
        self.assertFalse(any(call.startswith("release create") for call in self.gh_calls()))

    def test_reads_the_version_from_the_remote_branch_not_the_checkout(self) -> None:
        # An unpushed local bump must not name the release.
        write_version_files(self.repo, "0.9.0")
        self.tag()
        self.assertEqual(["v0", "v0.5.0"], self.remote_tags())


class CheckVersionTests(unittest.TestCase):
    """The propose job's check, which refuses a bumped version before the release pull request opens."""

    def setUp(self) -> None:
        self.remote, self.repo = released_clone(temporary_directory(self))

    def push_tags(self, *names: str) -> None:
        for name in names:
            run(self.repo, "git", "tag", "-a", name, "-m", name)
            run(self.repo, "git", "push", "--quiet", "origin", f"refs/tags/{name}")

    def check(self, version: str) -> tuple[int, str, str]:
        write_version_files(self.repo, version)
        out, err = io.StringIO(), io.StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            code = release.main(["check-version"], root=self.repo)
        return code, out.getvalue(), err.getvalue()

    def test_refuses_a_bump_below_the_newest_release(self) -> None:
        # After a revert from 0.6.0 to 0.5.0, a patch bump proposes 0.5.1.
        self.push_tags("v0.5.0", "v0.6.0", "v0")
        code, _, err = self.check("0.5.1")
        self.assertEqual(1, code)
        self.assertEqual("release: v0.6.0 is already released, so 0.5.1 cannot be; set a version above 0.6.0 "
                         "with .github/scripts/release.py set\n", err)

    def test_refuses_a_bump_to_a_version_already_tagged(self) -> None:
        # After the same revert, a minor bump proposes 0.6.0 again.
        self.push_tags("v0.5.0", "v0.6.0", "v0")
        code, _, err = self.check("0.6.0")
        self.assertEqual(1, code)
        self.assertEqual("release: v0.6.0 is already released; set a version above 0.6.0 "
                         "with .github/scripts/release.py set\n", err)

    def test_accepts_a_bump_above_every_release(self) -> None:
        code, out, _ = self.check("0.5.0")
        self.assertEqual((0, "no release is tagged yet, so 0.5.0 can be the first\n"), (code, out))
        # v0 and other tags that are not vX.Y.Z name no release.
        self.push_tags("v0.5.0", "v0", "v0.6.0-rc1")
        code, out, _ = self.check("0.5.1")
        self.assertEqual((0, "0.5.1 is above the newest release, v0.5.0\n"), (code, out))

    def test_reads_the_tags_the_remote_has_not_the_checkouts(self) -> None:
        run(self.repo, "git", "tag", "-a", "v0.9.0", "-m", "local only")
        self.assertEqual(0, self.check("0.5.1")[0])
        self.push_tags("v0.6.0")
        self.assertEqual(1, self.check("0.5.1")[0])


class WorkflowTests(unittest.TestCase):
    def test_the_propose_job_checks_the_version_before_it_commits_or_opens_the_pull_request(self) -> None:
        workflow = (ROOT / ".github" / "workflows" / "release.yml").read_text()
        steps = ["release.py bump", "release.py check-version", "git commit", "git push", "gh pr create"]
        positions = [workflow.find(step) for step in steps]
        self.assertNotIn(-1, positions, dict(zip(steps, positions)))
        self.assertEqual(sorted(positions), positions)


class RepoSlugTests(unittest.TestCase):
    def test_reads_github_remotes(self) -> None:
        for url in ("git@github.com:o/r.git", "ssh://git@github.com/o/r.git", "https://github.com/o/r.git",
                    "https://github.com/o/r"):
            self.assertEqual("o/r", release.repo_slug(url), url)
        self.assertEqual("", release.repo_slug("/tmp/remote.git"))


if __name__ == "__main__":
    unittest.main()
